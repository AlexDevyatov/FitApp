package ru.fitapp.ai

import ru.fitapp.domain.PortionRecalc

/**
 * Промпты разбора (§7 PLAN). Один системный префикс на все типы кадров плюс отдельный
 * текстовый запрос без фото — пересчёт КБЖУ после правки названия компонента.
 *
 * Запрещено в промптах: медицинские утверждения, диагнозы, советы. Разбор — только измерения.
 */
object AnalyzePrompts {

    /** Предел длины названия в текстовом запросе: защита от простыни из буфера обмена. */
    const val MAX_NAME_CHARS = 120

    /** Системный промпт разбора кадра — §7 PLAN, дословно с добавлением `drink`. */
    const val SYSTEM_PROMPT =
        "Ты анализируешь фотографию еды для дневника питания. Определи тип кадра: " +
            "`dish` — одно блюдо или продукт, `plate` — тарелка с несколькими компонентами, " +
            "`label` — этикетка или упаковка с составом, `drink` — напиток (чай, кофе, сок, " +
            "газировка, молочный напиток, коктейль), `not_food` — на фото нет еды. " +
            "Разбей кадр на компоненты и для каждого оцени вес в граммах и пищевую ценность " +
            "съеденной порции. Для этикетки бери данные из состава, а не угадывай. " +
            "Не занижай калорийность соусов, масла и обжарки. Для напитка оценивай сам напиток: " +
            "сахар, который добавили отдельно (ложка сахара в чай или кофе), не учитывай — " +
            "его отмечает пользователь. Уверенность `confidence` — " +
            "честная вероятность того, что разбор верен. `notes` — одна короткая фраза о том, " +
            "что может быть оценено неверно. Отвечай только JSON по схеме."

    /**
     * Текстовый запрос: пересчитать КБЖУ по названию и массе, без фотографии.
     * Ответ приходит по той же схеме, что и разбор кадра, ровно с одним компонентом.
     */
    fun estimate(name: String, grams: Double?): String {
        val cleanName = sanitizeName(name)
        val portion = if (grams != null && grams > 0.0) {
            "Масса порции: ${PortionRecalc.gramsToInput(grams)} г — считай пищевую ценность " +
                "ровно для этой массы и верни её же в поле grams."
        } else {
            "Масса порции неизвестна — оцени типичную порцию и укажи её в поле grams."
        }
        return "Оцени пищевую ценность порции для дневника питания без фотографии. " +
            "Название: «$cleanName». $portion " +
            "Верни kind = `dish` и ровно один компонент в items: поле name — " +
            "переданное название без изменений, граммы и КБЖУ этой порции, " +
            "ultra_processed — по составу. confidence — честная вероятность оценки. " +
            "notes — одна короткая фраза о том, что может быть оценено неверно. " +
            "Отвечай только JSON по схеме."
    }

    /** Название из пользовательского ввода: одна строка, без служебных символов, с пределом длины. */
    fun sanitizeName(name: String): String = name
        .replace('\n', ' ')
        .replace('\r', ' ')
        .replace('«', '"')
        .replace('»', '"')
        .trim()
        .take(MAX_NAME_CHARS)
}