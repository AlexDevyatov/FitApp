def read_token() -> str:
    token = os.environ.get("QWEN_API_TOKEN")
    if token:
        return token
    for parent in (ROOT, *ROOT.parents):
        env = parent / ".env"
        if env.is_file():
            for line in env.read_text(encoding="utf-8").splitlines():
                line = line.strip()
                if line.startswith("QWEN_API_TOKEN="):
                    return line.split("=", 1)[1].strip().strip('"').strip("'")
    raise SystemExit("QWEN_API_TOKEN не найден в окружении или .env")


def generate(name: str, prompt: str, seed: int | None, size: str) -> Path:
    token = read_token()
    payload = {
        "model": MODEL,
        "messages": [{"role": "user", "content": [{"type": "text", "text": prompt}]}],
        "parameters": {"size": size, "prompt_extend": False, "watermark": False},
    }
    if seed is not None:
        payload["parameters"]["seed"] = seed
    body = json.dumps(payload).encode("utf-8")

    ctx = ssl.create_default_context()
    ctx.check_hostname = False
    ctx.verify_mode = ssl.CERT_NONE

    last_error = ""
    for attempt in range(3):
        try:
            req = urllib.request.Request(
                f"{BASE_URL}/chat/completions",
                data=body,
                headers={
                    "Authorization": f"Bearer {token}",
                    "Content-Type": "application/json",
                },
                method="POST",
            )
            with urllib.request.urlopen(req, timeout=420, context=ctx) as resp:
                data = json.loads(resp.read().decode("utf-8"))
            content = data["output"]["choices"][0]["message"]["content"]
            url = next(part["image"] for part in content if part.get("type") == "image")
            break
        except Exception as exc:  # noqa: BLE001 — печатаем причину и повторяем
            last_error = str(exc)
            print(f"  попытка {attempt + 1}: {last_error}", file=sys.stderr)
            time.sleep(4 * (attempt + 1))
    else:
        raise SystemExit(f"{name}: генерация не удалась: {last_error}")

    OUT_DIR.mkdir(parents=True, exist_ok=True)
    target = OUT_DIR / f"{name}.png"
    with urllib.request.urlopen(url, timeout=180, context=ctx) as img:
        target.write_bytes(img.read())
    meta = {
        "name": name,
        "model": MODEL,
        "prompt": prompt,
        "seed": seed,
        "size": size,
        "usage": data.get("usage", {}),
    }
    (OUT_DIR / f"{name}.json").write_text(
        json.dumps(meta, ensure_ascii=False, indent=2), encoding="utf-8"
    )
    return target


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("names", nargs="*", help="имена экранов из SCREENS")
    parser.add_argument("--all", action="store_true", help="сгенерировать все экраны")
    parser.add_argument("--seed", type=int, default=None)
    parser.add_argument("--size", default="928*1664")
    parser.add_argument("--extra-style", default="", help="доп. слова стиля для всех экранов")
    args = parser.parse_args()

    names = list(SCREENS) if args.all else args.names
    unknown = [n for n in names if n not in SCREENS]
    if unknown:
        raise SystemExit(f"неизвестные экраны: {', '.join(unknown)}; есть: {', '.join(SCREENS)}")

    for name in names:
        base_style = DARK_STYLE if name in DARK_SCREENS else STYLE
        prompt = f"{base_style} {SCREENS[name]} {args.extra_style}".strip()
        print(f"[{name}] генерация…", flush=True)
        started = time.time()
        path = generate(name, prompt, args.seed, args.size)
        print(f"[{name}] готово за {time.time() - started:.0f}с -> {path}", flush=True)


if __name__ == "__main__":
    main()